"""Model validation helper (Phase 2): sensitivity sweeps + determinism checks.

Stdlib + repository code only (no new dependencies). Produces the tables used in
`research/validation/greenspace-v1.0.0.md` and `docs/_internal/evidence/model-sensitivity.md`.

Usage:
    python scripts/validate_model.py
    python scripts/validate_model.py --output docs/_internal/evidence/model-sensitivity.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

try:  # Windows consoles default to cp1252; the reports are UTF-8.
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # noqa: BLE001
    pass

from services.simulation_engine.runner import run_model  # noqa: E402

SEED = 42


def _run(model: str, parameters: dict) -> dict:
    return run_model(model, parameters, seed=SEED, compare_baseline=False)


def _sweep(
    model: str,
    base: dict,
    parameter: str,
    values: list,
    metric: str,
) -> list[tuple[str, float, float, float]]:
    rows = []
    for value in values:
        params = dict(base)
        params[parameter] = value
        result = _run(model, params)
        value_metric = result.get("metrics", {}).get(metric)
        if value_metric is None:
            continue
        interval = (result.get("uncertainty") or {}).get(metric) or [None, None]
        rows.append((str(value), float(value_metric), interval[0], interval[1]))
    return rows


def _table(header: tuple[str, str, str, str], rows: list[tuple]) -> str:
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] * len(header)) + "|",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def _determinism(model: str, parameters: dict) -> tuple[bool, dict, dict]:
    first = _run(model, parameters)
    second = _run(model, parameters)
    return first.get("metrics") == second.get("metrics"), first.get("metrics", {}), second.get("metrics", {})


def build_report() -> str:
    greenspace_base = {
        "area_id": "exarchia",
        "population": 10000,
        "park_count": 6,
        "avg_park_m2": 5000.0,
    }
    park_rows = _sweep(
        "greenspace", greenspace_base, "park_count", [0, 2, 4, 6, 8, 10, 12, 15, 20, 30], "green_m2_per_capita"
    )
    park_cover_rows = _sweep(
        "greenspace", greenspace_base, "park_count", [0, 2, 4, 6, 8, 10, 12, 15, 20, 30], "pct_within_300m"
    )
    size_rows = _sweep(
        "greenspace", greenspace_base, "avg_park_m2", [0, 1000, 2500, 5000, 7500, 10000, 20000], "green_m2_per_capita"
    )
    population_rows = _sweep(
        "greenspace", greenspace_base, "population", [5000, 8000, 10000, 12000, 15000, 20000], "green_m2_per_capita"
    )

    access_base = {"area_id": "exarchia", "max_walk_m": 500, "facility_count": 8, "population": 10000}
    walk_rows = _sweep(
        "accessibility", access_base, "max_walk_m", [100, 200, 300, 400, 500, 750, 1000, 1500, 2000], "accessibility_pct"
    )
    facility_rows = _sweep(
        "accessibility", access_base, "facility_count", [0, 2, 4, 6, 8, 10, 12, 15, 20], "accessibility_pct"
    )

    ok_green, green_first, green_second = _determinism("greenspace", greenspace_base)
    ok_access, access_first, _ = _determinism("accessibility", access_base)

    lines = [
        "# Model sensitivity & determinism report",
        "",
        "Generated by `python scripts/validate_model.py`.",
        "All runs use the deterministic synthetic fixtures (`seed=42`), no network access.",
        "",
        "## 1. Green space — sensitivity to park count",
        "",
        _table(("# parks", "m²/capita", "low", "high"), park_rows),
        "",
        "## 2. Green space — share of population within 300 m of a park",
        "",
        _table(("# parks", "% within 300 m", "low", "high"), park_cover_rows),
        "",
        "## 3. Green space — sensitivity to average park size",
        "",
        _table(("avg park m²", "m²/capita", "low", "high"), size_rows),
        "",
        "## 4. Green space — sensitivity to population",
        "",
        _table(("population", "m²/capita", "low", "high"), population_rows),
        "",
        "## 5. Walk accessibility — sensitivity to max walk distance",
        "",
        _table(("max walk m", "accessibility %", "low", "high"), walk_rows),
        "",
        "## 6. Walk accessibility — sensitivity to facility count",
        "",
        _table(("# facilities", "accessibility %", "low", "high"), facility_rows),
        "",
        "## 7. Determinism",
        "",
        f"- `greenspace`: two runs with seed 42 → identical metrics: **{ok_green}**",
        f"  - metrics: `{green_first}`",
        f"- `accessibility`: two runs with seed 42 → identical metrics: **{ok_access}**",
        f"  - metrics: `{access_first}`",
        "",
        "## Interpretation",
        "",
        "- Green m²/capita is linear in total park area and inverse-linear in population; both",
        "  are first-order drivers, so inputs must be measured, not guessed.",
        "- Park *count* drives 300 m coverage more strongly than m²/capita — fragmentation",
        "  matters. This is a substantive, falsifiable modelling choice.",
        "- Walk accessibility is a step function of `max_walk_m` and saturates once facilities",
        "  cover the synthetic population cloud; treat thresholds as policy levers.",
        "- The ±10 % / ±5 pp uncertainty bands are declared model uncertainty, not sampling",
        "  error. They are intentionally conservative and are shown next to every metric.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate model sensitivity tables.")
    parser.add_argument(
        "--output",
        default=str(ROOT / "docs" / "_internal" / "evidence" / "model-sensitivity.md"),
        help="Output markdown path",
    )
    args = parser.parse_args()
    report = build_report()
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(report, encoding="utf-8")
    print(report)
    print(f"\nWritten to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
